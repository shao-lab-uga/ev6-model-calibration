    'Color',[0.4660 0.6740 0.1880], ...
    'LineWidth',1.1);

grid on;
xlabel('Time [s]');
ylabel('Voltage [V]');
title('Battery voltage');
legend('EV6 dyno','77.4-kWh model', ...
    'Location','best');

nexttile;

plot(comparisonTime,dynoPower_kW, ...
    'k','LineWidth',1.3);

hold on;

plot(comparisonTime,simulatedPower_kW, ...
    'Color',[0.4660 0.6740 0.1880], ...
    'LineWidth',1.1);

grid on;
xlabel('Time [s]');
ylabel('Power [kW]');
title('Battery power');
legend('EV6 dyno','77.4-kWh model', ...
    'Location','best');

nexttile;

dynoCumulativeEnergy_Wh = ...
    1000*cumtrapz( ...
    comparisonTime,dynoPower_kW)/3600;

simulatedCumulativeEnergy_Wh = ...
    1000*cumtrapz( ...
    comparisonTime,simulatedPower_kW)/3600;

plot(comparisonTime,dynoCumulativeEnergy_Wh, ...
    'k','LineWidth',1.3);

hold on;

plot(comparisonTime, ...
    simulatedCumulativeEnergy_Wh, ...
    'Color',[0.4660 0.6740 0.1880], ...
    'LineWidth',1.1);

grid on;
xlabel('Time [s]');
ylabel('Net energy [Wh]');
title('Cumulative net energy');
legend('EV6 dyno','77.4-kWh model', ...
    'Location','best');

