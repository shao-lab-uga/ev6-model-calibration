%% 2023 EV6 77.4-kWh BATTERY VALIDATION: 5-60 SECONDS

projectRoot = ['C:\Users\ssl35511\Documents\MATLAB\ev6 dyno data\' ...
    'OneDrive_1_8-28-2026\Vehicles_24a\Vehicles\' ...
    'VehicleProjects\Bolt_EV'];

outputFolder = fullfile( ...
    projectRoot,'Run004_Professor_Figures');

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

%% Load compact simulated signals if needed

compactFile = fullfile( ...
    projectRoot, ...
    'EV6_Run004_77p4kWh_Corrected_60s_Battery.mat');

if ~exist('Run004_77p4_BattCurrentTS','var') || ...
   ~exist('Run004_77p4_BattVoltageTS','var')

    assert(isfile(compactFile), ...
        'The compact 77.4-kWh result file was not found.');

    load(compactFile);
end

%% Load Run 004 dyno data if needed

if ~exist('D004','var')

    run004File = ['C:\Users\ssl35511\Documents\MATLAB\ev6 dyno data\' ...
        'OneDrive_1_8-28-2026\EV6_drivecycleData\' ...
        'standards_test_08142026_004.mat'];

    loadedRun004 = load(run004File);

    D004 = ...
        loadedRun004.standards_test_08142026_004;
end

%% Locate dyno current and voltage

channelNames004 = erase( ...
    string({D004.Y.Name}),["<",">"]);

dynoCurrentIndex = find( ...
    channelNames004 == "VEH_batCurrent", ...
    1,'first');

dynoVoltageIndex = find( ...
    channelNames004 == "VEH_batVoltage", ...
    1,'first');

assert(~isempty(dynoCurrentIndex), ...
    'VEH_batCurrent was not found.');

assert(~isempty(dynoVoltageIndex), ...
    'VEH_batVoltage was not found.');

dynoCurrentTimeIndex = ...
    D004.Y(dynoCurrentIndex).XIndex;

dynoVoltageTimeIndex = ...
    D004.Y(dynoVoltageIndex).XIndex;

dynoCurrentTime = double( ...
    D004.X(dynoCurrentTimeIndex).Data(:));

dynoCurrentData = double( ...
    D004.Y(dynoCurrentIndex).Data(:));

dynoVoltageTime = double( ...
    D004.X(dynoVoltageTimeIndex).Data(:));

dynoVoltageData = double( ...
    D004.Y(dynoVoltageIndex).Data(:));

%% Establish common 5-60 second comparison time

simulatedCurrentTime = double( ...
    Run004_77p4_BattCurrentTS.Time(:));

simulatedCurrentData = double( ...
    Run004_77p4_BattCurrentTS.Data(:));

timeMask = ...
    simulatedCurrentTime >= 5 & ...
    simulatedCurrentTime <= 60;

comparisonTime = ...
    simulatedCurrentTime(timeMask);

simulatedCurrent = ...
    simulatedCurrentData(timeMask);

simulatedVoltage = interp1( ...
    double(Run004_77p4_BattVoltageTS.Time(:)), ...
    double(Run004_77p4_BattVoltageTS.Data(:)), ...
    comparisonTime, ...
    'linear',NaN);

dynoCurrent = interp1( ...
    dynoCurrentTime, ...
    dynoCurrentData, ...
    comparisonTime, ...
    'linear',NaN);

dynoVoltage = interp1( ...
    dynoVoltageTime, ...
    dynoVoltageData, ...
    comparisonTime, ...
    'linear',NaN);

valid = ...
    isfinite(comparisonTime) & ...
    isfinite(dynoCurrent) & ...
    isfinite(dynoVoltage) & ...
    isfinite(simulatedCurrent) & ...
    isfinite(simulatedVoltage);

comparisonTime = comparisonTime(valid);
dynoCurrent = dynoCurrent(valid);
dynoVoltage = dynoVoltage(valid);
simulatedCurrent = simulatedCurrent(valid);
simulatedVoltage = simulatedVoltage(valid);

%% Calculate power

dynoPower_kW = ...
    dynoVoltage .* dynoCurrent / 1000;

simulatedPower_kW = ...
    simulatedVoltage .* simulatedCurrent / 1000;

%% Calculate current, voltage and power metrics

signalNames = [
    "Battery Current"
    "Battery Voltage"
    "Battery Power"
    ];

signalUnits = [
    "A"
    "V"
    "kW"
    ];

measuredSignals = [
    dynoCurrent, ...
    dynoVoltage, ...
    dynoPower_kW
    ];

simulatedSignals = [
    simulatedCurrent, ...
    simulatedVoltage, ...
    simulatedPower_kW
    ];

Bias = nan(3,1);
MAE = nan(3,1);
RMSE = nan(3,1);
MaxAbsError = nan(3,1);
Correlation = nan(3,1);

for signalIndex = 1:3

    measurement = ...
        measuredSignals(:,signalIndex);

    simulation = ...
        simulatedSignals(:,signalIndex);

    signalError = simulation - measurement;

    Bias(signalIndex) = mean(signalError);
    MAE(signalIndex) = mean(abs(signalError));
    RMSE(signalIndex) = ...
        sqrt(mean(signalError.^2));

    MaxAbsError(signalIndex) = ...
        max(abs(signalError));

    measurementCentered = ...
        measurement - mean(measurement);

    simulationCentered = ...
        simulation - mean(simulation);

    Correlation(signalIndex) = ...
        sum(measurementCentered .* simulationCentered) / ...
        sqrt( ...
        sum(measurementCentered.^2) * ...
        sum(simulationCentered.^2));
end

ElectricalMetrics = table( ...
    signalNames, ...
    signalUnits, ...
    Bias, ...
    MAE, ...
    RMSE, ...
    MaxAbsError, ...
    Correlation, ...
    'VariableNames',{ ...
    'Signal', ...
    'Unit', ...
    'Bias', ...
    'MAE', ...
    'RMSE', ...
    'MaxAbsError', ...
    'Correlation'});

%% Calculate energy

dynoNetEnergy_kWh = ...
    trapz(comparisonTime,dynoPower_kW)/3600;

simulatedNetEnergy_kWh = ...
    trapz(comparisonTime,simulatedPower_kW)/3600;

dynoPositiveEnergy_kWh = ...
    trapz(comparisonTime,max(dynoPower_kW,0))/3600;

simulatedPositiveEnergy_kWh = ...
    trapz(comparisonTime,max(simulatedPower_kW,0))/3600;

dynoRegenEnergy_kWh = ...
    -trapz(comparisonTime,min(dynoPower_kW,0))/3600;

simulatedRegenEnergy_kWh = ...
    -trapz(comparisonTime,min(simulatedPower_kW,0))/3600;

energyLabels = [
    "EV6 dyno"
    "2023 EV6 77.4-kWh model"
    ];

NetEnergy_kWh = [
    dynoNetEnergy_kWh
    simulatedNetEnergy_kWh
    ];

PositiveEnergy_kWh = [
    dynoPositiveEnergy_kWh
    simulatedPositiveEnergy_kWh
    ];

RegenEnergyMagnitude_kWh = [
    dynoRegenEnergy_kWh
    simulatedRegenEnergy_kWh
    ];

EnergyMetrics = table( ...
    energyLabels, ...
    NetEnergy_kWh, ...
    PositiveEnergy_kWh, ...
    RegenEnergyMagnitude_kWh, ...
    'VariableNames',{ ...
    'Model', ...
    'NetEnergy_kWh', ...
    'PositiveEnergy_kWh', ...
    'RegenEnergyMagnitude_kWh'});

netEnergyError_Wh = ...
    1000*(simulatedNetEnergy_kWh - ...
    dynoNetEnergy_kWh);

positiveEnergyError_pct = ...
    100*(simulatedPositiveEnergy_kWh - ...
    dynoPositiveEnergy_kWh) / ...
    dynoPositiveEnergy_kWh;

regenEnergyError_pct = ...
    100*(simulatedRegenEnergy_kWh - ...
    dynoRegenEnergy_kWh) / ...
    dynoRegenEnergy_kWh;

%% Print results

fprintf('\n===== 2023 EV6 77.4-kWh VALIDATION =====\n');
fprintf('Comparison period = 5-60 seconds\n');
fprintf('Samples = %d\n\n',numel(comparisonTime));

disp(ElectricalMetrics);

fprintf('\n===== ENERGY RESULTS =====\n');
disp(EnergyMetrics);

fprintf('Net-energy difference = %.4f Wh\n', ...
    netEnergyError_Wh);

fprintf('Positive-energy error = %.3f %%\n', ...
    positiveEnergyError_pct);

fprintf('Regen-energy error = %.3f %%\n', ...
    regenEnergyError_pct);

fprintf('========================================\n');

