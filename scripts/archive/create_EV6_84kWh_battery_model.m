%% CREATE EV6 84-kWh BATTERY MODEL
% Creates a separate model copy and installs the battery candidate.
% It does not overwrite the torque-calibrated source model.

projectRoot = ['C:\Users\ssl35511\Documents\MATLAB\ev6 dyno data\' ...
    'OneDrive_1_8-28-2026\Vehicles_24a\Vehicles\' ...
    'VehicleProjects\Bolt_EV'];

sourceModel = 'EV6_LUT_FourWheelCalibratedCandidate';
batteryModel = 'EV6_LUT_FourWheel_EV6Battery84kWh';

parameterFile = fullfile( ...
    projectRoot,'EV6_84kWh_BatteryCandidate_Parameters.mat');

assert(isfile(parameterFile), ...
    'Battery candidate parameter file was not found.');

batteryParameters = load(parameterFile);

%% 1. Locate and copy source model

load_system(sourceModel);

sourceModelFile = which([sourceModel '.slx']);

assert(~isempty(sourceModelFile), ...
    'Could not locate the source model file.');

batteryModelFile = fullfile( ...
    projectRoot,[batteryModel '.slx']);

assert(~isfile(batteryModelFile), ...
    ['The battery candidate model already exists:\n%s\n' ...
     'Do not overwrite it automatically.'],batteryModelFile);

copyStatus = copyfile(sourceModelFile,batteryModelFile);

assert(copyStatus == 1, ...
    'Could not create the battery model copy.');

load_system(batteryModel);

fprintf('Created model copy:\n%s\n',batteryModelFile);

%% 2. Locate battery block in copied model

relativeBatteryPath = [ ...
    'Vehicle Under Test1/Vehicle/Battery/Battery/' ...
    'Lithium Ion Battery Pack1'];

batteryBlock84 = [batteryModel '/' relativeBatteryPath];

assert(getSimulinkBlockHandle(batteryBlock84) ~= -1, ...
    'Battery block was not found in the copied model.');

fprintf('Battery block:\n%s\n',batteryBlock84);

%% 3. Install candidate values in model workspace

batteryWorkspace = get_param( ...
    batteryModel,'ModelWorkspace');

assignin(batteryWorkspace, ...
    'EV6_BattSeriesCells', ...
    batteryParameters.EV6_BattSeriesCells);

assignin(batteryWorkspace, ...
    'EV6_BattParallelCells', ...
    batteryParameters.EV6_BattParallelCells);

assignin(batteryWorkspace, ...
    'EV6_BattPackCapacity_Ah', ...
    batteryParameters.EV6_BattPackCapacity_Ah);

assignin(batteryWorkspace, ...
    'EV6_BattCellCapacity_Ah', ...
    batteryParameters.EV6_BattCellCapacity_Ah);

assignin(batteryWorkspace, ...
    'EV6_BattInitialSOC', ...
    batteryParameters.EV6_Run004_InitialSOC);

assignin(batteryWorkspace, ...
    'EV6_BattOCV_Cell_V', ...
    batteryParameters.EV6_BattOCV_Cell_V);

assignin(batteryWorkspace, ...
    'EV6_BattOCV_SOC', ...
    batteryParameters.EV6_BattOCV_SOC);

assignin(batteryWorkspace, ...
    'EV6_BattResistanceTable_Ohm', ...
    batteryParameters.EV6_BattResistanceTable_Ohm);

assignin(batteryWorkspace, ...
    'EV6_BattResistanceTemp_K', ...
    batteryParameters.EV6_BattResistanceTemp_K);

assignin(batteryWorkspace, ...
    'EV6_BattResistanceSOC', ...
    batteryParameters.EV6_BattResistanceSOC);

assignin(batteryWorkspace, ...
    'EV6_TargetPackResistance_Ohm', ...
    batteryParameters.commonPackResistance_Ohm);

%% 4. Connect mask parameters to candidate variables

set_param(batteryBlock84, ...
    'CapacityCtrl','Parameter', ...
    'OutputVlt','Unfiltered', ...
    'BattChargeMax','EV6_BattCellCapacity_Ah', ...
    'Em','EV6_BattOCV_Cell_V', ...
    'CapLUTBp','EV6_BattOCV_SOC', ...
    'RInt','EV6_BattResistanceTable_Ohm', ...
    'BattTempBp','EV6_BattResistanceTemp_K', ...
    'CapSOCBp','EV6_BattResistanceSOC', ...
    'Ns','EV6_BattSeriesCells', ...
    'Np','EV6_BattParallelCells', ...
    'BattCapInit', ...
    'EV6_BattInitialSOC*EV6_BattCellCapacity_Ah');

%% 5. Resolve parameters from the block

resolvedNs = slResolve( ...
    'EV6_BattSeriesCells',batteryBlock84);

resolvedNp = slResolve( ...
    'EV6_BattParallelCells',batteryBlock84);

resolvedCellCapacity = slResolve( ...
    'EV6_BattCellCapacity_Ah',batteryBlock84);

resolvedInitialSOC = slResolve( ...
    'EV6_BattInitialSOC',batteryBlock84);

resolvedOCV = slResolve( ...
    'EV6_BattOCV_Cell_V',batteryBlock84);

resolvedOCVBreakpoints = slResolve( ...
    'EV6_BattOCV_SOC',batteryBlock84);

resolvedResistance = slResolve( ...
    'EV6_BattResistanceTable_Ohm',batteryBlock84);

resolvedResistanceTemperature = slResolve( ...
    'EV6_BattResistanceTemp_K',batteryBlock84);

resolvedResistanceSOC = slResolve( ...
    'EV6_BattResistanceSOC',batteryBlock84);

%% 6. Verify calculated starting conditions

initialCellOCV_V = interp1( ...
    resolvedOCVBreakpoints, ...
    resolvedOCV, ...
    resolvedInitialSOC, ...
    'linear');

initialPackOCV_V = resolvedNs*initialCellOCV_V;

initialCapacity_Ah = ...
    resolvedInitialSOC*resolvedCellCapacity;

initialCellResistance_Ohm = interp2( ...
    resolvedResistanceSOC, ...
    resolvedResistanceTemperature, ...
    resolvedResistance, ...
    resolvedInitialSOC, ...
    298.1, ...
    'linear');

initialPackResistance_Ohm = ...
    resolvedNs/resolvedNp * ...
    initialCellResistance_Ohm;

nominalPackCapacity_Ah = ...
    resolvedNp*resolvedCellCapacity;

nominalPackEnergy_kWh = ...
    697*nominalPackCapacity_Ah/1000;

%% 7. Save and attempt model update

save_system(batteryModel);

updateSucceeded = true;

try
    set_param(batteryModel,'SimulationCommand','update');
catch updateError
    updateSucceeded = false;

    fprintf('\nMODEL UPDATE NEEDS INITIALIZATION:\n%s\n', ...
        updateError.message);
end

save_system(batteryModel);

%% 8. Print verification

fprintf('\n===== EV6 84-kWh MODEL CREATED =====\n');
fprintf('Model = %s\n',batteryModel);
fprintf('Series cells = %d\n',resolvedNs);
fprintf('Parallel cells = %d\n',resolvedNp);
fprintf('Total cells = %d\n',resolvedNs*resolvedNp);
fprintf('Cell/branch capacity = %.3f Ah\n', ...
    resolvedCellCapacity);
fprintf('Total pack capacity = %.3f Ah\n', ...
    nominalPackCapacity_Ah);
fprintf('Nominal energy = %.3f kWh\n', ...
    nominalPackEnergy_kWh);
fprintf('Initial SOC = %.4f\n',resolvedInitialSOC);
fprintf('Initial capacity per branch = %.3f Ah\n', ...
    initialCapacity_Ah);
fprintf('Initial pack OCV = %.3f V\n', ...
    initialPackOCV_V);
fprintf('Initial pack resistance at 298.1 K = %.6f ohm\n', ...
    initialPackResistance_Ohm);

if updateSucceeded
    fprintf('Model update = SUCCESS\n');
else
    fprintf('Model update = NOT COMPLETED\n');
    fprintf('Run the normal EV6 initialization before simulation.\n');
end

fprintf('Saved to:\n%s\n',batteryModelFile);
fprintf('Original torque model was not modified.\n');
fprintf('======================================\n');

open_system(batteryBlock84);