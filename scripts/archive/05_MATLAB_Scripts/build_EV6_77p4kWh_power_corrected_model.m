%% BUILD 2023 EV6 77.4-kWh POWER-CORRECTED MODEL
% Creates a separate model. The original 77.4-kWh model is unchanged.

clearvars -except D001 D002 D003 D004

projectRoot = [ ...
    'C:\Users\ssl35511\Documents\MATLAB\ev6 dyno data\' ...
    'OneDrive_1_8-28-2026\Vehicles_24a\Vehicles\' ...
    'VehicleProjects\Bolt_EV'];

sourceModel = ...
    'EV6_LUT_FourWheel_EV6Battery77p4kWh';

targetModel = ...
    'EV6_LUT_FourWheel_EV6Battery77p4kWh_PowerCorrected';

sourceFile = fullfile(projectRoot,[sourceModel '.slx']);
targetFile = fullfile(projectRoot,[targetModel '.slx']);

mapFile = fullfile( ...
    projectRoot, ...
    'Battery_Calibration', ...
    'EV6_SpeedMode_PowerCorrection_Results.mat');

assert(isfile(sourceFile), ...
    'Source model was not found:\n%s',sourceFile);

assert(isfile(mapFile), ...
    'Correction-map file was not found:\n%s',mapFile);

assert(~isfile(targetFile), ...
    ['The target model already exists:\n%s\n' ...
     'Rename the existing target before running this script again.'], ...
     targetFile);

%% Load correction map

mapData = load(mapFile);

assert(mapData.candidatePasses, ...
    'The saved correction map did not pass its acceptance check.');

speedBp_mps = double(mapData.speedCenters_mps(:).');

tractionCorrection_kW = double( ...
    mapData.CorrectionMapTable. ...
    TractionCandidateCorrection_kW(:).');

regenCorrection_kW = double( ...
    mapData.CorrectionMapTable. ...
    RegenCandidateCorrection_kW(:).');

lowPowerCorrection_kW = double( ...
    mapData.CorrectionMapTable. ...
    LowPowerCandidateCorrection_kW(:).');

modeThreshold_kW = double(mapData.modeThreshold_kW);

assert(numel(speedBp_mps) == ...
       numel(tractionCorrection_kW));

assert(numel(speedBp_mps) == ...
       numel(regenCorrection_kW));

assert(numel(speedBp_mps) == ...
       numel(lowPowerCorrection_kW));

% Representative operating voltage used only to convert the
% empirical power correction into current.
%
% A constant avoids an algebraic loop between battery current
% and battery terminal voltage.
correctionVoltage_V = 726.5;

%% Copy original saved model

copyfile(sourceFile,targetFile);

load_system(targetModel);

batteryParent = [targetModel ...
    '/Vehicle Under Test1/Vehicle/Battery/Battery'];

batteryCurrentSum = [batteryParent '/Sum'];
frontCurrentSource = [batteryParent '/Bus Selector2'];
rearCurrentSource  = [batteryParent '/Bus Selector1'];

correctionSubsystem = [batteryParent ...
    '/EV6 Speed Mode Power Correction'];

speedFromBlock = [batteryParent ...
    '/EV6 Actual Vehicle Speed'];

assert(getSimulinkBlockHandle(batteryCurrentSum) ~= -1, ...
    'Battery-current Sum block was not found.');

assert(getSimulinkBlockHandle(frontCurrentSource) ~= -1, ...
    'Front current source was not found.');

assert(getSimulinkBlockHandle(rearCurrentSource) ~= -1, ...
    'Rear current source was not found.');

%% Find open space for new parent-level blocks

parentBlocks = find_system(batteryParent, ...
    'SearchDepth',1, ...
    'Type','Block');

maximumRight = 0;

for k = 1:numel(parentBlocks)
    blockPosition = get_param(parentBlocks{k},'Position');
    maximumRight = max(maximumRight,blockPosition(3));
end

x0 = maximumRight + 200;
y0 = 150;

%% Add global actual-speed From block

add_block( ...
    'simulink/Signal Routing/From', ...
    speedFromBlock, ...
    'GotoTag','vehSpeedSim', ...
    'Position',[x0 y0 x0+140 y0+30]);

%% Add correction subsystem

add_block( ...
    'simulink/Ports & Subsystems/Subsystem', ...
    correctionSubsystem, ...
    'Position',[x0+230 y0-20 x0+500 y0+170]);

Simulink.SubSystem.deleteContents(correctionSubsystem);

set_param(correctionSubsystem, ...
    'BackgroundColor','lightBlue');

%% Internal input and output ports

speedInput = [correctionSubsystem ...
    '/VehicleSpeed_mps'];

frontCurrentInput = [correctionSubsystem ...
    '/FrontCurrent_A'];

rearCurrentInput = [correctionSubsystem ...
    '/RearCurrent_A'];

correctionCurrentOutput = [correctionSubsystem ...
    '/CorrectionCurrent_A'];

correctionPowerOutput = [correctionSubsystem ...
    '/CorrectionPower_kW'];

basePowerOutput = [correctionSubsystem ...
    '/BasePower_kW'];

add_block('simulink/Ports & Subsystems/In1', ...
    speedInput, ...
    'Port','1', ...
    'Position',[30 75 60 89]);

add_block('simulink/Ports & Subsystems/In1', ...
    frontCurrentInput, ...
    'Port','2', ...
    'Position',[30 300 60 314]);

add_block('simulink/Ports & Subsystems/In1', ...
    rearCurrentInput, ...
    'Port','3', ...
    'Position',[30 360 60 374]);

add_block('simulink/Ports & Subsystems/Out1', ...
    correctionCurrentOutput, ...
    'Port','1', ...
    'Position',[950 95 980 109]);

add_block('simulink/Ports & Subsystems/Out1', ...
    correctionPowerOutput, ...
    'Port','2', ...
    'Position',[950 155 980 169]);

add_block('simulink/Ports & Subsystems/Out1', ...
    basePowerOutput, ...
    'Port','3', ...
    'Position',[950 305 980 319]);

%% Lookup tables

tractionLUT = [correctionSubsystem ...
    '/Traction Correction LUT'];

regenLUT = [correctionSubsystem ...
    '/Regen Correction LUT'];

lowPowerLUT = [correctionSubsystem ...
    '/Low Power Correction LUT'];

add_block( ...
    'simulink/Lookup Tables/1-D Lookup Table', ...
    tractionLUT, ...
    'BreakpointsForDimension1',mat2str(speedBp_mps,16), ...
    'Table',mat2str(tractionCorrection_kW,16), ...
    'Position',[180 35 350 85]);

add_block( ...
    'simulink/Lookup Tables/1-D Lookup Table', ...
    regenLUT, ...
    'BreakpointsForDimension1',mat2str(speedBp_mps,16), ...
    'Table',mat2str(regenCorrection_kW,16), ...
    'Position',[180 115 350 165]);

add_block( ...
    'simulink/Lookup Tables/1-D Lookup Table', ...
    lowPowerLUT, ...
    'BreakpointsForDimension1',mat2str(speedBp_mps,16), ...
    'Table',mat2str(lowPowerCorrection_kW,16), ...
    'Position',[180 195 350 245]);

% Clip corrections outside the trained speed range.
try
    set_param(tractionLUT,'ExtrapMethod','Clip');
    set_param(regenLUT,'ExtrapMethod','Clip');
    set_param(lowPowerLUT,'ExtrapMethod','Clip');
catch
    % Retain the installed MATLAB version's default if the
    % ExtrapMethod parameter is unavailable.
end

%% Calculate uncorrected battery power

baseCurrentSum = [correctionSubsystem ...
    '/Base Motor Current Sum'];

basePowerGain = [correctionSubsystem ...
    '/Base Current to Power'];

negativePowerGain = [correctionSubsystem ...
    '/Negative Base Power'];

add_block( ...
    'simulink/Math Operations/Add', ...
    baseCurrentSum, ...
    'Inputs','++', ...
    'Position',[180 305 215 365]);

add_block( ...
    'simulink/Math Operations/Gain', ...
    basePowerGain, ...
    'Gain',sprintf('%.15g/1000',correctionVoltage_V), ...
    'Position',[285 310 430 360]);

add_block( ...
    'simulink/Math Operations/Gain', ...
    negativePowerGain, ...
    'Gain','-1', ...
    'Position',[460 365 535 405]);

%% Select traction, regen, or low-power correction

regenOrLowSwitch = [correctionSubsystem ...
    '/Regen or Low Power'];

finalModeSwitch = [correctionSubsystem ...
    '/Traction or Other Mode'];

add_block( ...
    'simulink/Signal Routing/Switch', ...
    regenOrLowSwitch, ...
    'Criteria','u2 > Threshold', ...
    'Threshold',num2str(modeThreshold_kW,16), ...
    'Position',[500 145 565 225]);

add_block( ...
    'simulink/Signal Routing/Switch', ...
    finalModeSwitch, ...
    'Criteria','u2 > Threshold', ...
    'Threshold',num2str(modeThreshold_kW,16), ...
    'Position',[650 75 715 155]);

%% Convert selected correction from kW to A

powerToCurrent = [correctionSubsystem ...
    '/Power Correction to Current'];

add_block( ...
    'simulink/Math Operations/Gain', ...
    powerToCurrent, ...
    'Gain',sprintf('1000/%.15g',correctionVoltage_V), ...
    'Position',[790 80 900 130]);

%% Internal subsystem connections

connectBlocks(correctionSubsystem, ...
    speedInput,1,tractionLUT,1);

connectBlocks(correctionSubsystem, ...
    speedInput,1,regenLUT,1);

connectBlocks(correctionSubsystem, ...
    speedInput,1,lowPowerLUT,1);

connectBlocks(correctionSubsystem, ...
    frontCurrentInput,1,baseCurrentSum,1);

connectBlocks(correctionSubsystem, ...
    rearCurrentInput,1,baseCurrentSum,2);

connectBlocks(correctionSubsystem, ...
    baseCurrentSum,1,basePowerGain,1);

connectBlocks(correctionSubsystem, ...
    basePowerGain,1,negativePowerGain,1);

% Regen switch:
% u1 = regen correction
% u2 = negative base power
% u3 = low-power correction
connectBlocks(correctionSubsystem, ...
    regenLUT,1,regenOrLowSwitch,1);

connectBlocks(correctionSubsystem, ...
    negativePowerGain,1,regenOrLowSwitch,2);

connectBlocks(correctionSubsystem, ...
    lowPowerLUT,1,regenOrLowSwitch,3);

% Final switch:
% u1 = traction correction
% u2 = base power
% u3 = regen-or-low output
connectBlocks(correctionSubsystem, ...
    tractionLUT,1,finalModeSwitch,1);

connectBlocks(correctionSubsystem, ...
    basePowerGain,1,finalModeSwitch,2);

connectBlocks(correctionSubsystem, ...
    regenOrLowSwitch,1,finalModeSwitch,3);

connectBlocks(correctionSubsystem, ...
    finalModeSwitch,1,powerToCurrent,1);

connectBlocks(correctionSubsystem, ...
    powerToCurrent,1,correctionCurrentOutput,1);

connectBlocks(correctionSubsystem, ...
    finalModeSwitch,1,correctionPowerOutput,1);

connectBlocks(correctionSubsystem, ...
    basePowerGain,1,basePowerOutput,1);

%% Add diagnostic logging

correctionCurrentLog = [batteryParent ...
    '/Log EV6 Current Correction'];

correctionPowerLog = [batteryParent ...
    '/Log EV6 Power Correction'];

basePowerLog = [batteryParent ...
    '/Log EV6 Base Power'];

add_block( ...
    'simulink/Sinks/To Workspace', ...
    correctionCurrentLog, ...
    'VariableName','EV6CurrentCorrection_A', ...
    'SaveFormat','Timeseries', ...
    'Position',[x0+620 y0-20 x0+800 y0+10]);

add_block( ...
    'simulink/Sinks/To Workspace', ...
    correctionPowerLog, ...
    'VariableName','EV6PowerCorrection_kW', ...
    'SaveFormat','Timeseries', ...
    'Position',[x0+620 y0+50 x0+800 y0+80]);

add_block( ...
    'simulink/Sinks/To Workspace', ...
    basePowerLog, ...
    'VariableName','EV6BasePower_kW', ...
    'SaveFormat','Timeseries', ...
    'Position',[x0+620 y0+120 x0+800 y0+150]);

%% Add the third battery-current Sum input

set_param(batteryCurrentSum,'Inputs','|+++');

%% Parent-level connections

connectBlocks(batteryParent, ...
    speedFromBlock,1,correctionSubsystem,1);

connectBlocks(batteryParent, ...
    frontCurrentSource,1,correctionSubsystem,2);

connectBlocks(batteryParent, ...
    rearCurrentSource,1,correctionSubsystem,3);

connectBlocks(batteryParent, ...
    correctionSubsystem,1,batteryCurrentSum,3);

connectBlocks(batteryParent, ...
    correctionSubsystem,1,correctionCurrentLog,1);

connectBlocks(batteryParent, ...
    correctionSubsystem,2,correctionPowerLog,1);

connectBlocks(batteryParent, ...
    correctionSubsystem,3,basePowerLog,1);

%% Update and save

try
    set_param(targetModel,'SimulationCommand','update');

    updateSuccessful = true;

catch updateError
    updateSuccessful = false;

    fprintf('\n===== MODEL UPDATE FAILED =====\n');
    fprintf('%s\n',getReport( ...
        updateError,'extended','hyperlinks','off'));
end

if ~updateSuccessful
    error(['Stop here. The corrected model was not saved with ' ...
        'the new correction system.']);
end

save_system(targetModel,targetFile);

fprintf('\n===== POWER-CORRECTED MODEL CREATED =====\n');
fprintf('Model = %s\n',targetModel);
fprintf('Correction voltage = %.3f V\n', ...
    correctionVoltage_V);
fprintf('Mode threshold = %.3f kW\n', ...
    modeThreshold_kW);
fprintf('Battery Sum inputs = %s\n', ...
    get_param(batteryCurrentSum,'Inputs'));
fprintf('Model update = SUCCESS\n');
fprintf('Saved to:\n%s\n',targetFile);
fprintf('\nOriginal 77.4-kWh model was not modified.\n');
fprintf('Do not start the full simulation yet.\n');
fprintf('==========================================\n');

%% Local helper function

function connectBlocks(systemName, ...
    sourceBlock,sourcePortNumber, ...
    destinationBlock,destinationPortNumber)

    sourcePorts = get_param(sourceBlock,'PortHandles');
    destinationPorts = get_param( ...
        destinationBlock,'PortHandles');

    add_line( ...
        systemName, ...
        sourcePorts.Outport(sourcePortNumber), ...
        destinationPorts.Inport(destinationPortNumber), ...
        'autorouting','on');
end