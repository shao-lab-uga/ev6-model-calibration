%% CREATE 2023 EV6 WIND AWD 77.4-kWh BATTERY MODEL

projectRoot = ['C:\Users\ssl35511\Documents\MATLAB\ev6 dyno data\' ...
    'OneDrive_1_8-28-2026\Vehicles_24a\Vehicles\' ...
    'VehicleProjects\Bolt_EV'];

sourceModel = ...
    'EV6_LUT_FourWheel_EV6Battery84kWh';

targetModel = ...
    'EV6_LUT_FourWheel_EV6Battery77p4kWh';

targetFile = fullfile( ...
    projectRoot,[targetModel '.slx']);

%% Confirm source model

load_system(sourceModel);

sourceFile = get_param(sourceModel,'FileName');

assert(isfile(sourceFile), ...
    'The 84-kWh source model file was not found.');

assert(~isfile(targetFile), ...
    ['The 77.4-kWh model already exists:\n%s\n' ...
    'Stop here so it is not overwritten.'], ...
    targetFile);

%% Find battery block in source model

sourceBlocks = find_system( ...
    sourceModel, ...
    'LookUnderMasks','all', ...
    'FollowLinks','on', ...
    'Type','Block');

sourceBatteryBlock = '';

requiredParameters = { ...
    'BattChargeMax', ...
    'Em', ...
    'CapLUTBp', ...
    'RInt', ...
    'BattTempBp', ...
    'CapSOCBp', ...
    'Ns', ...
    'Np', ...
    'BattCapInit'};

for blockIndex = 1:numel(sourceBlocks)

    try
        dialogParameters = get_param( ...
            sourceBlocks{blockIndex}, ...
            'DialogParameters');

        if isstruct(dialogParameters) && ...
                all(isfield( ...
                dialogParameters,requiredParameters))

            sourceBatteryBlock = ...
                sourceBlocks{blockIndex};

            break
        end
    catch
    end
end

assert(~isempty(sourceBatteryBlock), ...
    'The battery block was not found.');

fprintf('\nSource battery block:\n%s\n', ...
    sourceBatteryBlock);

%% Resolve the current 84-kWh battery data

sourceOCVTable = double(slResolve( ...
    get_param(sourceBatteryBlock,'Em'), ...
    sourceBatteryBlock));

sourceOCVBreakpoints = double(slResolve( ...
    get_param(sourceBatteryBlock,'CapLUTBp'), ...
    sourceBatteryBlock));

sourceResistanceTable = double(slResolve( ...
    get_param(sourceBatteryBlock,'RInt'), ...
    sourceBatteryBlock));

sourceTemperatureBreakpoints = double(slResolve( ...
    get_param(sourceBatteryBlock,'BattTempBp'), ...
    sourceBatteryBlock));

sourceSOCBreakpoints = double(slResolve( ...
    get_param(sourceBatteryBlock,'CapSOCBp'), ...
    sourceBatteryBlock));

sourceSeriesCells = double(slResolve( ...
    get_param(sourceBatteryBlock,'Ns'), ...
    sourceBatteryBlock));

sourceParallelCells = double(slResolve( ...
    get_param(sourceBatteryBlock,'Np'), ...
    sourceBatteryBlock));

sourceBranchCapacity_Ah = double(slResolve( ...
    get_param(sourceBatteryBlock,'BattChargeMax'), ...
    sourceBatteryBlock));

sourceInitialCapacity_Ah = double(slResolve( ...
    get_param(sourceBatteryBlock,'BattCapInit'), ...
    sourceBatteryBlock));

sourceInitialSOC = ...
    sourceInitialCapacity_Ah / ...
    sourceBranchCapacity_Ah;

%% Calculate 2023 EV6 capacity

officialEnergy_kWh = 77.4;
officialNominalVoltage_V = 697;

targetPackCapacity_Ah = ...
    officialEnergy_kWh*1000 / ...
    officialNominalVoltage_V;

targetBranchCapacity_Ah = ...
    targetPackCapacity_Ah / ...
    sourceParallelCells;

targetInitialCapacity_Ah = ...
    sourceInitialSOC * ...
    targetBranchCapacity_Ah;

initialCellOCV_V = interp1( ...
    sourceOCVBreakpoints, ...
    sourceOCVTable, ...
    sourceInitialSOC, ...
    'linear','extrap');

initialPackOCV_V = ...
    sourceSeriesCells * initialCellOCV_V;

%% Copy model without modifying source

copyStatus = copyfile(sourceFile,targetFile);

assert(copyStatus == 1, ...
    'The model copy could not be created.');

load_system(targetModel);

%% Find battery block in copied model

targetBlocks = find_system( ...
    targetModel, ...
    'LookUnderMasks','all', ...
    'FollowLinks','on', ...
    'Type','Block');

targetBatteryBlock = '';

for blockIndex = 1:numel(targetBlocks)

    try
        dialogParameters = get_param( ...
            targetBlocks{blockIndex}, ...
            'DialogParameters');

        if isstruct(dialogParameters) && ...
                all(isfield( ...
                dialogParameters,requiredParameters))

            targetBatteryBlock = ...
                targetBlocks{blockIndex};

            break
        end
    catch
    end
end

assert(~isempty(targetBatteryBlock), ...
    'The battery block was not found in the copied model.');

%% Store unique battery variables inside model workspace

modelWorkspace = get_param( ...
    targetModel,'ModelWorkspace');

assignin(modelWorkspace, ...
    'EV6_2023_BattEnergy_kWh', ...
    officialEnergy_kWh);

assignin(modelWorkspace, ...
    'EV6_2023_BattNominalVoltage_V', ...
    officialNominalVoltage_V);

assignin(modelWorkspace, ...
    'EV6_2023_BattNumCellsSeries', ...
    sourceSeriesCells);

assignin(modelWorkspace, ...
    'EV6_2023_BattNumCellsParallel', ...
    sourceParallelCells);

assignin(modelWorkspace, ...
    'EV6_2023_BattBranchCapacity_Ah', ...
    targetBranchCapacity_Ah);

assignin(modelWorkspace, ...
    'EV6_2023_BattPackCapacity_Ah', ...
    targetPackCapacity_Ah);

assignin(modelWorkspace, ...
    'EV6_2023_InitialSOC', ...
    sourceInitialSOC);

assignin(modelWorkspace, ...
    'EV6_2023_InitialPackOCV_V', ...
    initialPackOCV_V);

assignin(modelWorkspace, ...
    'EV6_2023_BattOpenVoltTbl', ...
    sourceOCVTable);

assignin(modelWorkspace, ...
    'EV6_2023_BattOpenVoltCapBpts', ...
    sourceOCVBreakpoints);

assignin(modelWorkspace, ...
    'EV6_2023_BattResistTbl', ...
    sourceResistanceTable);

assignin(modelWorkspace, ...
    'EV6_2023_BattResistTempBpts', ...
    sourceTemperatureBreakpoints);

assignin(modelWorkspace, ...
    'EV6_2023_BattResistSocBpts', ...
    sourceSOCBreakpoints);

%% Connect battery mask to unique model variables

set_param(targetBatteryBlock, ...
    'BattChargeMax', ...
    'EV6_2023_BattBranchCapacity_Ah');

set_param(targetBatteryBlock, ...
    'Em', ...
    'EV6_2023_BattOpenVoltTbl');

set_param(targetBatteryBlock, ...
    'CapLUTBp', ...
    'EV6_2023_BattOpenVoltCapBpts');

set_param(targetBatteryBlock, ...
    'RInt', ...
    'EV6_2023_BattResistTbl');

set_param(targetBatteryBlock, ...
    'BattTempBp', ...
    'EV6_2023_BattResistTempBpts');

set_param(targetBatteryBlock, ...
    'CapSOCBp', ...
    'EV6_2023_BattResistSocBpts');

set_param(targetBatteryBlock, ...
    'Ns', ...
    'EV6_2023_BattNumCellsSeries');

set_param(targetBatteryBlock, ...
    'Np', ...
    'EV6_2023_BattNumCellsParallel');

set_param(targetBatteryBlock, ...
    'BattCapInit', ...
    ['EV6_2023_InitialSOC*' ...
    'EV6_2023_BattBranchCapacity_Ah']);

% Set the voltage-filter initial condition consistently
try
    set_param(targetBatteryBlock, ...
        'Vinit', ...
        'EV6_2023_InitialPackOCV_V');
catch
    warning('Vinit was not changed, but it is not required for unfiltered output.');
end

%% Update and save

try
    set_param(targetModel, ...
        'SimulationCommand','update');

    updateStatus = "SUCCESS";

catch updateError

    updateStatus = "FAILED";

    fprintf('\n%s\n',getReport( ...
        updateError,'extended', ...
        'hyperlinks','off'));

    error('Stop here. Do not run the simulation.');
end

save_system(targetModel);

fprintf('\n===== 2023 EV6 77.4-kWh MODEL CREATED =====\n');
fprintf('Model = %s\n',targetModel);
fprintf('Official energy = %.3f kWh\n', ...
    officialEnergy_kWh);
fprintf('Official nominal voltage = %.1f V\n', ...
    officialNominalVoltage_V);
fprintf('Equivalent series cells = %.0f\n', ...
    sourceSeriesCells);
fprintf('Equivalent parallel cells = %.0f\n', ...
    sourceParallelCells);
fprintf('Pack capacity = %.3f Ah\n', ...
    targetPackCapacity_Ah);
fprintf('Capacity per branch = %.3f Ah\n', ...
    targetBranchCapacity_Ah);
fprintf('Initial SOC = %.5f\n', ...
    sourceInitialSOC);
fprintf('Initial branch capacity = %.3f Ah\n', ...
    targetInitialCapacity_Ah);
fprintf('Initial pack OCV = %.3f V\n', ...
    initialPackOCV_V);
fprintf('Model update = %s\n',updateStatus);
fprintf('Saved to:\n%s\n',targetFile);
fprintf('============================================\n');