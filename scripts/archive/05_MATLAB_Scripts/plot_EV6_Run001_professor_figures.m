%% Local functions

function [runIDs,runNames,runDuration, ...
    hasWheelTorque,hasCalibrationSignals] = ...
    inventoryEV6Runs()

runIDs = Simulink.sdi.getAllRunIDs;
numberOfRuns = numel(runIDs);

runNames = strings(numberOfRuns,1);
runDuration = nan(numberOfRuns,1);
hasWheelTorque = false(numberOfRuns,1);
hasCalibrationSignals = false(numberOfRuns,1);

for k = 1:numberOfRuns
    currentRun = Simulink.sdi.getRun(runIDs(k));
    runNames(k) = string(currentRun.Name);

    signalIDs = currentRun.getAllSignalIDs;
    signalNames = strings(numel(signalIDs),1);

    for n = 1:numel(signalIDs)
        signal = Simulink.sdi.getSignal(signalIDs(n));
        signalNames(n) = string(signal.Name);
    end

    wheelIndex = find( ...
        signalNames == "SimWhlTrq_LF_Nm", ...
        1,'first');

    hasWheelTorque(k) = ~isempty(wheelIndex);

    hasCalibrationSignals(k) = ...
        any(signalNames == ...
        "MotTrqCmdTrac_Calibrated") || ...
        any(signalNames == ...
        "MotTrqCmdRegen_Calibrated");

    if ~isempty(wheelIndex)
        wheelSignal = Simulink.sdi.getSignal( ...
            signalIDs(wheelIndex));

        runDuration(k) = max(double( ...
            wheelSignal.Values.Time(:)));
    end
end
end

function [wheelTorque,endTime] = ...
    extractWheelTorque( ...
    sdiRun,targetTime,wheelSignalNames)

signalIDs = sdiRun.getAllSignalIDs;
signalNames = strings(numel(signalIDs),1);

for k = 1:numel(signalIDs)
    signal = Simulink.sdi.getSignal(signalIDs(k));
    signalNames(k) = string(signal.Name);
end

wheelTorque = nan(numel(targetTime),4);
endTime = inf;

for j = 1:4
    signalIndex = find( ...
        signalNames == wheelSignalNames(j), ...
        1,'first');

    assert(~isempty(signalIndex), ...
        'Signal missing from %s: %s', ...
        sdiRun.Name,wheelSignalNames(j));

    signal = Simulink.sdi.getSignal( ...
        signalIDs(signalIndex));

    signalTime = double(signal.Values.Time(:));
    signalData = double(signal.Values.Data(:));

    [uniqueTime,uniqueIndex] = ...
        unique(signalTime,'stable');

    uniqueData = signalData(uniqueIndex);

    wheelTorque(:,j) = interp1( ...
        uniqueTime,uniqueData,targetTime, ...
        'linear',NaN);

    endTime = min(endTime,uniqueTime(end));
end
end

function comparison = ...
    buildTorqueComparison(wheelTorque)

comparison = [
    wheelTorque, ...
    wheelTorque(:,1) + wheelTorque(:,2), ...
    wheelTorque(:,3) + wheelTorque(:,4), ...
    sum(wheelTorque,2)
];
end

function limits = calculateTorqueLimits( ...
    firstSeries,secondSeries,plotIndex)

limits = zeros(6,2);

for j = 1:6
    values = [
        firstSeries(plotIndex,j)
        secondSeries(plotIndex,j)
    ];

    minimumValue = min(values);
    maximumValue = max(values);

    padding = 0.05* ...
        (maximumValue-minimumValue);

    if padding == 0
        padding = 1;
    end

    limits(j,:) = [
        minimumValue-padding, ...
        maximumValue+padding
    ];
end
end

function limits = calculateThreeSeriesLimits( ...
    firstSeries,secondSeries,thirdSeries,plotIndex)

limits = zeros(6,2);

for j = 1:6
    values = [
        firstSeries(plotIndex,j)
        secondSeries(plotIndex,j)
        thirdSeries(plotIndex,j)
    ];

    minimumValue = min(values);
    maximumValue = max(values);

    padding = 0.05* ...
        (maximumValue-minimumValue);

    if padding == 0
        padding = 1;
    end

    limits(j,:) = [
        minimumValue-padding, ...
        maximumValue+padding
    ];
end
end

function figureHandle = createTwoSeriesFigure( ...
    time,firstSeries,secondSeries, ...
    plotIndex,limits, ...
    firstColor,secondColor, ...
    plotTitles,firstLegend,secondLegend, ...
    mainTitle)

figureHandle = figure( ...
    'Color','w', ...
    'Position',[50 50 1500 900]);

layout = tiledlayout(3,2, ...
    'TileSpacing','compact', ...
    'Padding','compact');

for j = 1:6
    nexttile;

    plot(time(plotIndex), ...
        firstSeries(plotIndex,j), ...
        'Color',firstColor, ...
        'LineWidth',0.8);

    hold on;

    plot(time(plotIndex), ...
        secondSeries(plotIndex,j), ...
        'Color',secondColor, ...
        'LineWidth',0.8);

    grid on;
    ylim(limits(j,:));
    title(plotTitles(j));
    xlabel('Time [s]');
    ylabel('Torque [N·m]');

    legend(firstLegend,secondLegend, ...
        'Location','best');
end

title(layout,mainTitle);
end

